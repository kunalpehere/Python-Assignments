# 1. Create a string fruit = "watermelon". 
# Print the first and last character using positive indexing, 
# and then print the same two characters using negative indexing.

fruit = "watermelon"

print("First Character of fruit string using positive indexing is", fruit[0])
print("Last Character of fruit string using positive indexing is", fruit[9])
print("First Character of fruit string using negative indexing is", fruit[-1])
print("Last Character of fruit string using negative indexing is", fruit[-10])