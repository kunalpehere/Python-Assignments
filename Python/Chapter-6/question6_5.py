# 5. A user enters their name as name = "aNiL kUmAr". 
# Print the name in lowercase, uppercase, swapped case, 
# capitalized and title case.

name = "aNil kUmAr"

LowerCase_name = name.lower()
UpperCase_name = name.upper()
SwappedCase_name = name.swapcase()
CapitalizedCase_name = name.capitalize()
TitleCase_name = name.title()

print(LowerCase_name)
print(UpperCase_name)
print(SwappedCase_name)
print(CapitalizedCase_name)
print(TitleCase_name)