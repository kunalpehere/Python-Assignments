# 7️⃣ Predict the output of the following code and explain why.

a = 10
b = 10.5
c = 2 + 3j
d = True
e = "Python"
f = None

print(type(a))  # Output -> <class 'int'>, because it's a whole number.
print(type(b))  # Output -> <class 'float'> because it's contains a decimal point
print(type(c))  # Output -> <class 'complex'> because it contains an imaginary value 'j'
print(type(d))  # Output -> <class 'bool'> because it contains a boolean value.
print(type(e))  # Output -> <class 'str'> because it contains a string value which is enclosed in double inverted commas
print(type(f))  # Output -> <class 'NoneType'> because it represents the absence of a value.