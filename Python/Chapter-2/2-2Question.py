# 2️⃣ Write a Python program to demonstrate why keywords such as for, if, and class cannot be used as variable names.

# for = 2 # -> we get SyntaxError: invalid syntax

# if = 33 # -> we get SyntaxError: invalid syntax

# class = "B" # -> we get SyntaxError: invalid syntax

# Answer
# Keywords such as for, if, and class are reserved words in Python.
# Each keyword has a specific purpose and meaning in Python.
# Therefore, we cannot use these keywords as variable names.
# If we try to use them as variable names, Python raises a
# SyntaxError: invalid syntax.
