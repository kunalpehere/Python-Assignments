# 9️⃣ Write a Python program to convert the following numbers into decimal values:

# Binary: 1010
# Octal: 12
# Hexadecimal: A

Binary = int("1010", 2)
Octal = int("12", 8)
Hexadecimal = int("A", 16)

print("Binary to Decimal:", Binary)
print("Octal to Decimal:", Octal)
print("Hexadecimal to Decimal:", Hexadecimal)