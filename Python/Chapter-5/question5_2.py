# 2. Create a string code = "Zebra@2026". 
# Print the smallest and largest character using min() and max(). 
# Then print the ord() value of both characters to explain the result.

code = "Zebra@2026"

print(min(code)) # Output -> 0
print(max(code)) # Output -> r
print(ord("0")) # Output -> 48
print(ord("r")) # Output -> 114
