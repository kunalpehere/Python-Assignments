# 3. Create two variables x = 47 and y = 6. 
# Print the result of all seven arithmetic operations (+, -, *, /, //, %, **) between them, 
# and also print the type of each result.

x = 47
y = 6

Addition = x + y
print(x + y, type(Addition))

Subtraction = x - y
print(x - y, type(Subtraction))

Multiplication = x * y
print(x * y, type(Multiplication))

Division = x / y
print(x / y, type(Division))

Floor_Division = x // y
print(x // y, type(Floor_Division))

Modulus = x % y
print(x % y, type(Modulus))

Exponentiation = x ** y
print(x ** y, type(Exponentiation))